// Kadr Player — the bridge between the page and the main process
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (fn) => { const f = (e, v) => fn(v); ipcRenderer.on(ch, f); return () => ipcRenderer.removeListener(ch, f); };

contextBridge.exposeInMainWorld('kadr', {
  init: call('app:init'),
  ffmpegVersion: call('app:ffmpeg-version'),
  saveSettings: call('settings:set'),
  saveState: call('state:set'),
  probe: call('media:probe'),
  findInPage: call('media:find-in-page'),
  listMovies: call('catalog:list'),
  generateCaptions: call('captions:generate'),
  cancelCaptions: call('captions:cancel'),
  saveCaptions: call('captions:save'),
  onCaptionProgress: on('captions:progress'),
  movieDetails: call('catalog:movie-details'),
  seriesDetails: call('catalog:series'),
  playMovie: call('catalog:play'),
  movieAction: call('catalog:action'),
  onMovieKey: on('catalog:key'),
  onMoviePointer: on('catalog:pointer'),
  onMovieMenu: on('catalog:menu'),
  encoders: call('media:encoders'),
  cropdetect: call('media:cropdetect'),
  subEmbedded: call('media:sub-embedded'),
  readText: call('media:read-text'),
  findSubs: call('media:find-subs'),
  gpuInfo: call('gpu:info'),
  gpuStatus: call('gpu:feature-status'),
  openFiles: call('dialog:open-files'),
  openFolder: call('dialog:open-folder'),
  openSubtitle: call('dialog:open-subtitle'),
  savePlaylist: call('dialog:save-playlist'),
  expand: call('files:expand'),
  stat: call('file:stat'),
  showFile: call('file:show'),
  external: call('open:external'),
  clipboardText: call('clipboard:text'),
  saveShot: call('screenshot:save'),
  fullscreen: call('win:fullscreen'),
  onTop: call('win:on-top'),
  minimize: call('win:minimize'),
  title: call('win:title'),
  progress: call('win:progress'),
  overlay: call('win:overlay'),
  mini: call('win:mini'),
  fitVideo: call('win:fit-video'),
  powerBlock: call('power:block'),
  menu: call('menu:popup'),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return file && file.path || ''; } },
  onOpen: on('open-files'),
  onFullscreen: on('fullscreen'),
  onMaximized: on('maximized'),
  onGpuCrash: on('gpu-crash'),
  test: {
    shot: call('test:shot'),
    log: call('test:log'),
    quit: call('test:quit'),
    script: call('test:script'),
  },
});
