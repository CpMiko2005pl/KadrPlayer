// One-off asset step: copies the Inter font files and turns the Lucide icons we use into src/js/icons.js
// node scripts/make-assets.js [path-to-lucide-static/icons]
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lucide = process.argv[2] || path.join(root, 'node_modules', 'lucide-static', 'icons');
const names = ['play', 'pause', 'skip-back', 'skip-forward', 'square', 'volume-2', 'volume-1', 'volume-x', 'volume', 'captions', 'audio-lines',
  'settings-2', 'sliders-horizontal', 'list-video', 'maximize', 'minimize', 'picture-in-picture-2', 'gauge', 'camera', 'folder-open', 'file-video',
  'link', 'x', 'repeat', 'repeat-1', 'shuffle', 'plus', 'trash-2', 'save', 'menu', 'info', 'rotate-cw', 'chevron-right', 'film', 'monitor', 'music',
  'rewind', 'fast-forward', 'grip-vertical', 'crop', 'sparkles', 'history', 'external-link', 'keyboard', 'heart', 'scan', 'pin', 'cpu',
  'wand-sparkles', 'zap', 'clapperboard', 'hammer', 'shield-check', 'arrow-down-to-line'];
const icons = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(lucide, n + '.svg'), 'utf8');
  icons[n] = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(root, 'src', 'js', 'icons.js'),
  '// Lucide icons (ISC License, https://lucide.dev) — generated by scripts/make-assets.js\n' +
  'window.K = window.K || {};\nK.ICONS = ' + JSON.stringify(icons, null, 0).replace(/","/g, '",\n"') + ';\n' +
  "K.icon = (n, cls) => `<svg class=\"ic${cls ? ' ' + cls : ''}\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\">${K.ICONS[n] || ''}</svg>`;\n");

const fdir = path.join(root, 'node_modules', '@fontsource', 'inter', 'files');
const out = path.join(root, 'src', 'fonts');
fs.mkdirSync(out, { recursive: true });
for (const w of [400, 500, 600, 700, 800]) for (const s of ['latin', 'latin-ext']) {
  fs.copyFileSync(path.join(fdir, `inter-${s}-${w}-normal.woff2`), path.join(out, `inter-${s}-${w}.woff2`));
}
console.log('icons + fonts written');
